/**
 * The HTTP contract between the UI and the (mocked) backend.
 * Documented for humans in docs/API.md. Keep the two in sync.
 */
import type {
  Classification,
  ClassificationSummary,
  ParameterId,
  Patient,
  Range,
  ReferenceConfig,
  Sex,
} from '../domain';

export type { Patient };

export interface LatestResultSummary extends ClassificationSummary {
  recordedAt: string;
}

/** GET /api/patients item. */
export interface PatientListItem extends Patient {
  latestResult: LatestResultSummary | null;
}

/** POST /api/patients body. */
export interface CreatePatientRequest {
  name: string;
  age: number;
  sex: Sex;
}

/** GET /api/parameters response. */
export type ReferenceConfigResponse = ReferenceConfig;

/** A saved value, classified by the server. */
export interface ResultValue {
  parameterId: ParameterId;
  value: number;
  unit: string;
  classification: Classification;
  /**
   * Snapshot of the ranges used when this value was classified, so history
   * stays truthful even if the configuration changes later.
   */
  referenceRange: {
    normal: Range;
    critical: Range;
  };
}

export interface ResultEntry {
  id: string;
  patientId: string;
  /** ISO 8601, set by the server when the entry is saved. */
  recordedAt: string;
  values: ResultValue[];
  summary: ClassificationSummary;
}

/** POST /api/patients/:patientId/results body. */
export interface SaveResultRequest {
  /**
   * Generated by the client once per draft and reused on retry. The server
   * returns the already-saved entry for a repeated id instead of saving twice.
   */
  clientRequestId: string;
  values: Partial<Record<ParameterId, number>>;
}

export type ApiErrorCode = 'VALIDATION_FAILED' | 'BAD_REQUEST' | 'NOT_FOUND' | 'INTERNAL_ERROR';

export interface ApiFieldError {
  code: string;
  message: string;
}

export interface ApiErrorBody {
  error: {
    code: ApiErrorCode;
    message: string;
    /** Keyed by form field: a parameter id, or name/age/sex for patients. */
    fieldErrors?: Record<string, ApiFieldError>;
    /** Errors that belong to the whole request, e.g. "enter at least one value". */
    formErrors?: string[];
  };
}
